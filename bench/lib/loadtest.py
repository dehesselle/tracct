"""Load test for the tracct daemon: its cost and its losses under sustained load.

Runs against the installed unit (it does not install or restart anything) and drives
three phases, each measured on its own:

  steady  long-lived clients, one TCP connection each, 8 bytes per 500 ms, long argv
  churn   one process sending UDP to many distinct ports: connection cardinality per drain
  exec    short-lived processes, one UDP datagram each: exec events and late attribution

Per phase it reports the daemon's CPU and PSS (whole process tree, like resprof in the
matrix), connection rows written per second, how many of the generated bytes were
recorded under the generator's command line, and the daemon's warnings in the journal
(ring buffer drops, near-capacity maps, write retries, ...).

usage: sudo python3 lib/loadtest.py [--phases steady,churn,exec] [--seconds 60]
                                    [--clients 300] [--ports 30000] [--rate 30000]
                                    [--execs 300] [--out results/loadtest.json]
"""

from __future__ import annotations

import argparse
import asyncio
import json
import re
import sqlite3
import subprocess
import sys
import threading
import time
import tomllib
from pathlib import Path

from resprof import ResProfiler

BENCH = Path(__file__).resolve().parent.parent
BENCHLOAD = BENCH / "bin" / "benchload"
DB = "/var/lib/tracct/tracct.db"
CONFIG = Path("/etc/opt/tracct/config.toml")
SINK_PORT = 9300
CHURN_PORT = 20000
# below the ephemeral range, so no other row has a remote port in it
EXEC_PORT, EXEC_PORTS = 10000, 5000
PAD = "x" * 4000

# journal lines worth counting, by what they mean for the measurement
WARNINGS = {
    "exec ring drop": re.compile(r"exec ring buffer full"),
    "dns ring drop": re.compile(r"dns ring buffer full"),
    "map near capacity": re.compile(r"near capacity"),
    "write retry": re.compile(r"SQLite execute|retry buffer full"),
    "live feed drop": re.compile(r"live feed: dropped"),
    "sync error": re.compile(r"sync error|thread timeout"),
}


def sh(cmd: str) -> str:
    return subprocess.run(
        cmd, shell=True, text=True, capture_output=True
    ).stdout.strip()


def daemon_pids() -> list[int]:
    pid = sh("systemctl show -p MainPID --value tracct")
    return [int(pid)] if pid.isdigit() and int(pid) > 0 else []


def write_limit() -> int:
    try:
        return int(
            tomllib.loads(CONFIG.read_text())
            .get("database", {})
            .get("write_limit_seconds", 10)
        )
    except (OSError, ValueError, tomllib.TOMLDecodeError):
        return 10


def query(sql: str, params: tuple = ()) -> list:
    con = sqlite3.connect(f"file:{DB}?mode=ro", uri=True, timeout=30)
    try:
        return con.execute(sql, params).fetchall()
    finally:
        con.close()


def max_rowid() -> int:
    return query("SELECT COALESCE(MAX(rowid), 0) FROM connections")[0][0]


def journal_cursor() -> str:
    out = sh("journalctl -u tracct -n 0 --show-cursor --no-pager")
    m = re.search(r"-- cursor: (\S+)", out)
    return m.group(1) if m else ""


def journal_warnings(cursor: str) -> dict:
    out = (
        sh(f"journalctl -u tracct --after-cursor='{cursor}' -o cat --no-pager")
        if cursor
        else ""
    )
    lines = [
        line
        for line in out.splitlines()
        if "tracct.error" in line or "Traceback" in line
    ]
    counts = {
        name: sum(1 for line in lines if rx.search(line))
        for name, rx in WARNINGS.items()
    }
    counts["other"] = len(lines) - sum(counts.values())
    return {"counts": counts, "samples": lines[:8]}


def results_sent(procs: list[subprocess.Popen]) -> int:
    total = 0
    for p in procs:
        out, _ = p.communicate()
        m = re.search(r"RESULT sent=(\d+)", out or "")
        total += int(m.group(1)) if m else 0
    return total


def recorded_sent(tag: str, after_rowid: int) -> int:
    return query(
        "SELECT COALESCE(SUM(c.send), 0) FROM connections c JOIN executables e ON c.exe_id = e.id WHERE c.rowid > ? AND instr(e.cmdline, ?) > 0",
        (after_rowid, tag),
    )[0][0]


class Sink(threading.Thread):
    """TCP server the steady clients talk to; reads and discards."""

    def __init__(self, port: int) -> None:
        super().__init__(daemon=True)
        self.port = port
        self.ready = threading.Event()

    def run(self) -> None:
        async def handle(reader, writer):
            while await reader.read(65536):
                pass
            writer.close()

        async def main():
            server = await asyncio.start_server(
                handle, "127.0.0.1", self.port, backlog=4096
            )
            self.ready.set()
            async with server:
                await server.serve_forever()

        asyncio.run(main())


def phase_steady(tag: str, args) -> dict:
    sink = Sink(SINK_PORT)
    sink.start()
    sink.ready.wait(10)
    procs = [
        subprocess.Popen(
            [
                str(BENCHLOAD),
                "tcp",
                str(SINK_PORT),
                "500",
                str(args.seconds),
                f"{tag}-{i}-{PAD}",
            ],
            stdout=subprocess.PIPE,
            text=True,
        )
        for i in range(args.clients)
    ]
    return {"generated": {"processes": args.clients}, "sent": results_sent(procs)}


def phase_churn(tag: str, args) -> dict:
    p = subprocess.Popen(
        [
            str(BENCHLOAD),
            "churn",
            str(CHURN_PORT),
            str(args.ports),
            str(args.rate),
            str(args.seconds),
            tag,
        ],
        stdout=subprocess.PIPE,
        text=True,
    )
    return {
        "generated": {"ports": args.ports, "datagrams_per_sec": args.rate},
        "sent": results_sent([p]),
    }


def phase_exec(tag: str, args) -> dict:
    running: list[subprocess.Popen] = []
    sent = n = 0
    start = time.monotonic()
    while time.monotonic() - start < args.seconds:
        for _ in range(max(1, args.execs // 10)):
            running.append(
                subprocess.Popen(
                    [str(BENCHLOAD), "once", str(EXEC_PORT + n % EXEC_PORTS), tag],
                    stdout=subprocess.PIPE,
                    text=True,
                )
            )
            n += 1
        time.sleep(0.1)
        done = [p for p in running if p.poll() is not None]
        running = [p for p in running if p.poll() is None]
        sent += results_sent(done)
    sent += results_sent(running)
    return {
        "generated": {"processes": n, "per_sec": round(n / args.seconds)},
        "sent": sent,
    }


PHASES = {"steady": phase_steady, "churn": phase_churn, "exec": phase_exec}


def run_phase(name: str, args) -> dict:
    tag = f"loadtest-{name}-{int(time.time())}"
    flush = 2 * write_limit() + 5
    before, cursor = max_rowid(), journal_cursor()
    prof = ResProfiler(daemon_pids)
    prof.start()
    t0 = time.monotonic()
    out = PHASES[name](tag, args)
    elapsed = time.monotonic() - t0
    prof.stop()
    # let the last windows reach the database before counting
    time.sleep(flush)
    after = max_rowid()
    if name == "exec":
        # the processes are gone before most drains, so their command lines are too:
        # find their bytes by destination port, and see which executable they got
        by_exe = query(
            "SELECT e.exe, SUM(c.send) FROM connections c JOIN executables e ON c.exe_id = e.id WHERE c.rowid > ? AND c.rport >= ? AND c.rport < ? GROUP BY e.exe",
            (before, EXEC_PORT, EXEC_PORT + EXEC_PORTS),
        )
        out["sent_by_exe"] = {exe or "(unresolved)": sent for exe, sent in by_exe}
        recorded = sum(sent for _, sent in by_exe)
    else:
        recorded = recorded_sent(tag, before)
    out.update(
        seconds=round(elapsed, 1),
        rows_per_sec=round((after - before) / elapsed, 1),
        recorded=recorded,
        recorded_pct=round(100.0 * recorded / out["sent"], 2) if out["sent"] else None,
        daemon=prof.summary(),
        journal=journal_warnings(cursor),
    )
    return out


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--phases", default="steady,churn,exec")
    ap.add_argument("--seconds", type=float, default=60)
    ap.add_argument("--clients", type=int, default=300, help="steady: client processes")
    ap.add_argument(
        "--ports", type=int, default=30000, help="churn: distinct destination ports"
    )
    ap.add_argument(
        "--rate", type=int, default=30000, help="churn: datagrams per second"
    )
    ap.add_argument("--execs", type=int, default=300, help="exec: processes per second")
    ap.add_argument("--out", default=str(BENCH / "results" / "loadtest.json"))
    args = ap.parse_args()
    if not BENCHLOAD.exists():
        print(
            f"missing {BENCHLOAD} (compile the helpers first: sudo bash lib/build.sh)",
            file=sys.stderr,
        )
        return 2
    if not daemon_pids():
        print("the tracct unit is not running", file=sys.stderr)
        return 2
    report = {
        "version": sh("/opt/tracct/bin/tracct --version"),
        "write_limit_seconds": write_limit(),
        "phases": {},
    }
    for name in args.phases.split(","):
        print(f"== {name} ({args.seconds:g}s) ...", flush=True)
        res = run_phase(name, args)
        report["phases"][name] = res
        d = res["daemon"] or {}
        print(
            f"   cpu avg {d.get('cpu_avg_pct')}% p95 {d.get('cpu_p95_pct')}%  pss avg {d.get('pss_avg_mb')} MB peak {d.get('pss_peak_mb')} MB  "
            f"rows/s {res['rows_per_sec']}  recorded {res['recorded_pct']}% of {res['sent']} B",
            flush=True,
        )
        print(f"   journal {res['journal']['counts']}", flush=True)
        if "sent_by_exe" in res:
            print(f"   bytes by executable {res['sent_by_exe']}", flush=True)
    Path(args.out).parent.mkdir(parents=True, exist_ok=True)
    Path(args.out).write_text(json.dumps(report, indent=2))
    print(f"wrote {args.out}", flush=True)
    return 0


if __name__ == "__main__":
    sys.exit(main())
